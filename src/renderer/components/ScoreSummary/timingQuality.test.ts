describe('timingQualityReceipt', () => {
  it('keeps Superheroes at its scored and target windows without conflating them', () => {
    const records = [
      ...superhero_deltas.map((deltaMs) => ({
        tick: 0,
        timeSeconds: 0,
        deltaMs,
        element: 'snare' as const,
        verdict: 'hit' as const,
      })),
      ...Array.from({ length: 43 }, () => ({
        tick: 0,
        timeSeconds: 0,
        deltaMs: 0,
        element: 'snare' as const,
        verdict: 'miss' as const,
      })),
    ];
    const summary = {
      ...summarizeRun(records, '2026-08-17T00:00:00.000Z'),
      timingWindowMs: 200,
      timingGapMs: 180,
    };
    const receipt = timingQualityReceipt(summary, records);

    expect(receipt).toMatchObject({
      meanMs: 2,
      medianMs: 1,
      spreadMs: 49,
      insideThirtyPercent: 71,
      scoredWindowPercent: 92,
      targetWindowMs: 60,
      targetWindowPercent: 86,
    });
  });
});
